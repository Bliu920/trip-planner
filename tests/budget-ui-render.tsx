import assert from "node:assert/strict";
import { createRequire } from "node:module";
import { renderToStaticMarkup } from "react-dom/server";
import { tableBudget } from "./budget-ui-fixture";
import { budgetTotals } from "../lib/budget";
const require=createRequire(import.meta.url);
require.extensions[".css"]=()=>{};
const {BudgetDetails,CostEvidence}=require("../lib/budget/ui/table") as typeof import("../lib/budget/ui/table");
const noop=()=>{};
const html=renderToStaticMarkup(<BudgetDetails budget={tableBudget} onOpenDocument={noop}/>);
assert.equal((html.match(/<table/g)??[]).length,1);
assert.equal((html.match(/class="bd-cost-row"/g)??[]).length,6);
assert.doesNotMatch(html,/bd-group|bd-cost\"|Published room rates|One room shared/);
assert.match(html,/Estimated subtotal/);
assert.match(html,/€433 to €583/);
assert.match(html,/not estimated.*not included above/);
assert.match(html,/<strong>€0<\/strong>/);
assert.match(html,/Not estimated/);
assert.equal((html.match(/aria-expanded="false"/g)??[]).length,6);
assert.equal(new Set([...html.matchAll(/aria-controls="([^"]+)"/g)].map(match=>match[1])).size,6);
assert.match(html,/<caption class="sr-only">Budget breakdown/);
assert.match(html,/<th scope="row">Two nights in Florence/);
const calc=renderToStaticMarkup(<CostEvidence entry={tableBudget.entries[0]} amount="€220 to €280" onOpenDocument={noop}/>);
assert.match(calc,/2.*×.*€110 to €140.*=.*€220 to €280/);
assert.match(calc,/href="https:\/\/example.com\/room-rates"[^>]*target="_blank"[^>]*rel="noopener noreferrer"/);
assert.match(calc,/27 Oct 2026/);
assert.match(calc,/One room shared by two adults/);
const document=renderToStaticMarkup(<CostEvidence entry={tableBudget.entries[1]} amount="€15" onOpenDocument={noop}/>);
assert.match(document,/Open document/);
assert.match(document,/source version 2/);
const unknown=renderToStaticMarkup(<CostEvidence entry={tableBudget.entries[5]} amount="Not estimated" onOpenDocument={noop}/>);
assert.match(unknown,/Arrival airport and time/);
assert.doesNotMatch(unknown,/€0|How this is calculated/);
const allUnknown={...tableBudget,entries:[tableBudget.entries[5]]};
const missing=renderToStaticMarkup(<BudgetDetails budget={allUnknown} onOpenDocument={noop}/>);
assert.match(missing,/Not estimated yet/);
assert.doesNotMatch(missing,/<strong>€0/);
assert.deepEqual(budgetTotals(tableBudget),{min:433,max:583,confirmed:15,priced:5,unknown:1});
console.log("Budget table, calculation, source and missing-price checks passed.");
